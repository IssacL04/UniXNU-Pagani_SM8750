// OnePlus 13T (PKX110) board glue of the A830 driver, installed as kits/oneplus13t (ARCHITECTURE 3.1, 3.5). It does
// three things only: fill Adreno830Board from the generated device-tree constants (package/PaganiGpuInputs.h) and the
// embedded firmware, parse the pagani-gpu-* boot arguments, and run adreno830_start(). Every hardware action belongs to
// the driver. Stage7Probe calls pagani_gpu_start() once, after the display and the peripherals started, when
// pagani-gpu=1.
#include <IOKit/IOLib.h>
#include <kern/thread.h>
#include <pexpert/pexpert.h>
#include "Adreno830Board.h"
#include "PaganiGpuInputs.h"
#include "PaganiGpuFirmwarePins.h"   // generated by scripts/build-pagani-gpu.py from scripts/data/sm8750-gpu-inputs.json

// The images of scripts/build-pagani-gpu.py (strong), or the driver's weak zero-length defaults without firmware.
extern "C" const uint8_t native_adreno_firmware_image[],native_adreno_sqe_firmware_image[],
    native_adreno_aqe_firmware_image[],native_adreno_zap_image[];
extern "C" const uint64_t native_adreno_firmware_image_size,native_adreno_sqe_firmware_image_size,
    native_adreno_aqe_firmware_image_size,native_adreno_zap_image_size;

namespace {
Adreno830Board board;
bool started;

static_assert(PAGANI_GPU_IRQ_SMMU_CB_COUNT==4 && PAGANI_GPU_DDR_KBPS_COUNT<=255 && PAGANI_GPU_CNOC_LEVELS_COUNT==2 &&
              PAGANI_GPU_GMU_KHZ_COUNT==2 && PAGANI_GPU_GMU_VLVL_COUNT==2 && PAGANI_GPU_BIN_COUNT==Adreno830BinCount &&
              PAGANI_GPU_WINDOW_LLCC_COUNT==Adreno830LlccWindows,"generated table sizes match Adreno830Board");
static_assert(PAGANI_GPU_BIN0_COUNT<=Adreno830LevelMax && PAGANI_GPU_BIN1_COUNT<=Adreno830LevelMax &&
              PAGANI_GPU_BIN2_COUNT<=Adreno830LevelMax && PAGANI_GPU_BIN3_COUNT<=Adreno830LevelMax &&
              PAGANI_GPU_BIN4_COUNT<=Adreno830LevelMax && PAGANI_GPU_BIN5_COUNT<=Adreno830LevelMax &&
              PAGANI_GPU_COMMON_LEVEL_COUNT<=PAGANI_GPU_BIN0_COUNT,"power-level bins fit the driver's tables");
const uint32_t ddrKbps[]=PAGANI_GPU_DDR_KBPS;
// qcom,gpu-pwrlevel-bins in DT order, each table ascending (GMU level = index + 1).
const Adreno830Level bin0[]=PAGANI_GPU_BIN0_LEVELS,bin1[]=PAGANI_GPU_BIN1_LEVELS,bin2[]=PAGANI_GPU_BIN2_LEVELS,
    bin3[]=PAGANI_GPU_BIN3_LEVELS,bin4[]=PAGANI_GPU_BIN4_LEVELS,bin5[]=PAGANI_GPU_BIN5_LEVELS;
const Adreno830Level *const binLevels[Adreno830BinCount]={bin0,bin1,bin2,bin3,bin4,bin5};
const uint8_t binCounts[Adreno830BinCount]={PAGANI_GPU_BIN0_COUNT,PAGANI_GPU_BIN1_COUNT,PAGANI_GPU_BIN2_COUNT,
    PAGANI_GPU_BIN3_COUNT,PAGANI_GPU_BIN4_COUNT,PAGANI_GPU_BIN5_COUNT};

Adreno830Firmware image(const uint8_t *bytes,uint64_t length,const uint8_t (&pin)[32])
{
    Adreno830Firmware firmware={bytes,length,{}};
    for(unsigned i=0;i<32;++i)firmware.sha256[i]=pin[i];
    return firmware;
}

// Every input of ARCHITECTURE 3.5 from the generated constants: windows, identity, interrupts, streams, the six
// power-level bins with their speed-bin/SKU match data and initial levels (qcom,initial-pwrlevel, the DT index), the
// common level count, the bus and GMU tables, UBWC and the firmware pointers. The driver selects and checks the levels.
void fillBoard(Adreno830Board *b)
{
    *b={};
    b->magic=Adreno830BoardMagic;b->version=Adreno830BoardVersion;
    b->gpu=PAGANI_GPU_WINDOW_GPU;b->rscc=PAGANI_GPU_WINDOW_RSCC;b->cx_dbgc=PAGANI_GPU_WINDOW_CX_DBGC;
    b->cx_misc=PAGANI_GPU_WINDOW_CX_MISC;b->gmu=PAGANI_GPU_WINDOW_GMU;b->gmu_ao=PAGANI_GPU_WINDOW_GMU_AO;
    b->gpucc=PAGANI_GPU_WINDOW_GPUCC;b->gcc=PAGANI_GPU_WINDOW_GCC;b->smmu=PAGANI_GPU_WINDOW_SMMU;
    b->cmd_db=PAGANI_GPU_WINDOW_CMD_DB;b->smem=PAGANI_GPU_WINDOW_SMEM;b->zap=PAGANI_GPU_WINDOW_ZAP;
    b->qfprom=PAGANI_GPU_WINDOW_QFPROM;b->rsc_drv2=PAGANI_GPU_WINDOW_RSC_DRV2;
    b->aoss_msgram=PAGANI_GPU_WINDOW_AOSS_MSGRAM;b->ipcc=PAGANI_GPU_WINDOW_IPCC;b->tsens_tm=PAGANI_GPU_WINDOW_TSENS_TM;
    const Adreno830Window llcc[]=PAGANI_GPU_WINDOW_LLCC;
    for(unsigned i=0;i<Adreno830LlccWindows;++i)b->llcc[i]=llcc[i];
    b->chip_id=PAGANI_GPU_CHIP_ID;
    b->soc_id=PAGANI_GPU_SOC_ID;   // SMEM socinfo of PKX110 (measured); S0 compares it with the live value
    b->irq_gpu=PAGANI_GPU_IRQ_GPU;b->irq_cx_host=PAGANI_GPU_IRQ_CX_HOST;b->irq_hfi=PAGANI_GPU_IRQ_HFI;b->irq_gmu=PAGANI_GPU_IRQ_GMU;
    b->irq_smmu_global=PAGANI_GPU_IRQ_SMMU_GLOBAL;
    const uint32_t banks[]=PAGANI_GPU_IRQ_SMMU_CB;
    for(unsigned i=0;i<4;++i)b->irq_smmu_cb[i]=banks[i];
    b->irq_scm_waitq=PAGANI_GPU_IRQ_SCM_WAITQ;
    b->sid_gpu=PAGANI_GPU_SID_GPU;b->sid_lpac=PAGANI_GPU_SID_LPAC;b->sid_gmu=PAGANI_GPU_SID_GMU;
    // Context policy of ARCHITECTURE 4.5.4: GPU on CB0 through stream-match slot 0 (LPAC slot 3), GMU on CB2 through
    // slot 1; the driver moves to the next free slot when a preferred one is taken.
    b->slot_gpu=0;b->slot_lpac=3;b->slot_gmu=1;b->cb_gpu=0;b->cb_gmu=2;
    b->smmu_actlr=0x303;   // measured: of the DT value PAGANI_GPU_SMMU_ACTLR_DT only 0x303 sticks under the hypervisor
    b->pool_mib=512;
    b->qfprom_speedbin_offset=PAGANI_GPU_QFPROM_SPEEDBIN_OFFSET;b->speedbin_bits=PAGANI_GPU_SPEEDBIN_BITS;
    const uint32_t speed[]=PAGANI_GPU_BIN_SPEED,skuCount[]=PAGANI_GPU_BIN_SKU_COUNT,sku[][Adreno830BinSkus]=PAGANI_GPU_BIN_SKU,
        initial[]=PAGANI_GPU_BIN_INITIAL;
    for(unsigned i=0;i<Adreno830BinCount;++i) {
        b->levels[i]=binLevels[i];b->level_count[i]=binCounts[i];b->initial_level[i]=uint8_t(initial[i]);
        b->bin_speed[i]=speed[i];b->bin_sku_count[i]=skuCount[i];
        for(unsigned k=0;k<Adreno830BinSkus;++k)b->bin_sku[i][k]=sku[i][k];
    }
    b->common_level_count=PAGANI_GPU_COMMON_LEVEL_COUNT;
    b->ddr_kbps=ddrKbps;b->ddr_levels=uint8_t(PAGANI_GPU_DDR_KBPS_COUNT);
    const uint32_t cnoc[]=PAGANI_GPU_CNOC_LEVELS,gmuKhz[]=PAGANI_GPU_GMU_KHZ,gmuVlvl[]=PAGANI_GPU_GMU_VLVL;
    for(unsigned i=0;i<2;++i) {b->cnoc_levels[i]=cnoc[i];b->gmu_khz[i]=gmuKhz[i];b->gmu_vlvl[i]=gmuVlvl[i];}
    b->ubwc_mode=PAGANI_GPU_UBWC_MODE;b->min_access_length=PAGANI_GPU_MIN_ACCESS_LENGTH;
    b->highest_bank_bit=16;   // Gen8 constant (ARCHITECTURE 3.2 D, 4.14.3), not a DT value
    b->gmu_fw=image(native_adreno_firmware_image,native_adreno_firmware_image_size,PAGANI_GPU_FW_GMU_SHA256);
    b->sqe_fw=image(native_adreno_sqe_firmware_image,native_adreno_sqe_firmware_image_size,PAGANI_GPU_FW_SQE_SHA256);
    b->aqe_fw=image(native_adreno_aqe_firmware_image,native_adreno_aqe_firmware_image_size,PAGANI_GPU_FW_AQE_SHA256);
    b->zap_fw=image(native_adreno_zap_image,native_adreno_zap_image_size,PAGANI_GPU_FW_ZAP_SHA256);
}

bool bootArgument(void *,const char *name,uint32_t *value)
{
    return PE_parse_boot_argn(name,value,sizeof *value);
}

// ARCHITECTURE 3.6; the names, defaults and flag bits are the driver's (Adreno830ParseKnobs).
void parseKnobs(Adreno830Board *b) {Adreno830ParseKnobs(b,bootArgument,nullptr);}

void runAsync(void *,wait_result_t) {adreno830_start(&board);}
}

extern "C" void pagani_gpu_trace_start(void);

extern "C" void pagani_gpu_start(void)
{
    if(__atomic_exchange_n(&started,true,__ATOMIC_ACQ_REL))return;
    fillBoard(&board);
    parseKnobs(&board);
    if(board.knobs.async==1) {
        // Kernel debugging only: backboardd may look for Metal before the service exists (ARCHITECTURE 3.1).
        thread_t thread=nullptr;
        if(kernel_thread_start(runAsync,nullptr,&thread)==KERN_SUCCESS) {thread_deallocate(thread);return;}
    }
    adreno830_start(&board);
    pagani_gpu_trace_start();
}
