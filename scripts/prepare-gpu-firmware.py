#!/usr/bin/env python3
"""Validate the pinned PKX110 Gen8 inputs and emit a Mach-O firmware assembly unit."""
import argparse
import hashlib
import json
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[1]
PINS = ROOT / 'scripts/data/sm8750-gpu-inputs.json'
FILES = (('gmu', 'gen80000_gmu.bin'), ('sqe', 'gen80000_sqe.fw'),
         ('aqe', 'gen80000_aqe.fw'), ('zap', 'gen80000_zap.mbn'))


def zap_parts(data):
    if len(data) < 52 or data[:7] != b'\x7fELF\x01\x01\x01' or struct.unpack_from('<HHI', data, 16) != (2, 164, 1):
        raise ValueError('Expected little-endian Qualcomm ELF32 ZAP image')
    phoff = struct.unpack_from('<I', data, 28)[0]
    size, count = struct.unpack_from('<HH', data, 42)
    if size != 32 or not 2 <= count <= 16 or phoff < 52 or phoff + count * size > len(data):
        raise ValueError('Invalid ZAP program header table')
    headers = [struct.unpack_from('<8I', data, phoff + i * size) for i in range(count)]
    hashes = [p for p in headers if (p[6] >> 24) & 7 == 2]
    loads = [p for p in headers if p[0] == 1 and (p[6] >> 24) & 7 != 2 and p[5]]
    if headers[0][0] == 1 or len(hashes) != 1 or not loads:
        raise ValueError('Missing ZAP metadata, hash or load segment')
    head_bytes = headers[0][4]
    hash_header = hashes[0]
    if head_bytes < phoff + count * size or head_bytes > len(data) or not hash_header[4] or \
            hash_header[1] < head_bytes or hash_header[1] + hash_header[4] > len(data) or \
            head_bytes + hash_header[4] > 0x4000:
        raise ValueError('Invalid ZAP metadata extents')
    low = min(p[3] for p in loads)
    high = max((p[3] + p[5] + 0xfff) & ~0xfff for p in loads)
    if low & 0xfff or high - low > 0x2000:
        raise ValueError('ZAP load does not fit the DT reservation')
    payload = bytearray(high - low)
    spans = []
    for p in loads:
        start, length = p[3] - low, p[5]
        if not p[6] & (1 << 27) or p[4] > length or p[1] + p[4] > len(data) or \
                p[3] + length > 0x100000000 or any(start < b and a < start + length for a, b in spans):
            raise ValueError('Invalid or overlapping relocatable ZAP load segment')
        spans.append((start, start + length))
        payload[start:start + p[4]] = data[p[1]:p[1] + p[4]]
    return data[:head_bytes] + data[hash_header[1]:hash_header[1] + hash_header[4]], bytes(payload)


def prepare(source, output):
    pins = json.loads(PINS.read_text())['firmware']['files']
    images = []
    for symbol, name in FILES:
        data = (source / name).read_bytes()
        pin = pins[name]
        if len(data) != pin['bytes'] or hashlib.sha256(data).hexdigest() != pin['sha256']:
            raise ValueError(f'{name}: size or SHA-256 differs from the pinned backup')
        images.append((symbol, name, data))
    metadata, payload = zap_parts(images[-1][2])
    images += [('zap_metadata', 'zap-metadata.bin', metadata), ('zap_payload', 'zap-payload.bin', payload)]
    # All inputs pass before producing files. The firmware directory stays local.
    output.mkdir(parents=True, exist_ok=True)
    assembly = ['.section __DATA_CONST,__const']
    header = ['/* Generated by prepare-gpu-firmware.py. */', '#pragma once', '#include <stdint.h>',
              '#ifdef __cplusplus', 'extern "C" {', '#endif']
    for symbol, name, data in images:
        dest = output / name
        dest.write_bytes(data)
        label = 'sm8750_gpu_' + symbol
        assembly += ['.p2align 12', '.globl _' + label, '_' + label + ':',
                     '.incbin ' + json.dumps(str(dest.resolve())), '_' + label + '_end:',
                     '.p2align 3', '.globl _' + label + '_size', '_' + label + '_size:',
                     '.quad _' + label + '_end-_' + label]
        header += ['extern const uint8_t ' + label + '[];',
                   'extern const uint64_t ' + label + '_size;']
    header += ['#ifdef __cplusplus', '}', '#endif']
    (output / 'firmware.S').write_text('\n'.join(assembly) + '\n')
    (output / 'Sm8750GpuFirmware.h').write_text('\n'.join(header) + '\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--firmware-dir', type=Path, default=ROOT / '.cache/firmware/pkx110-gpu')
    parser.add_argument('--output', type=Path, default=ROOT / 'out/oneplus13t/gpu')
    args = parser.parse_args()
    try:
        prepare(args.firmware_dir, args.output)
    except (OSError, ValueError, KeyError) as error:
        parser.exit(1, f'{error}\n')
    print(f'PASS: four pinned Gen8 images; assembly and header in {args.output}')


if __name__ == '__main__':
    main()
