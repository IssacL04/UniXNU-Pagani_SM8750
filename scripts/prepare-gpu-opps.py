#!/usr/bin/env python3
"""Generate the PKX110 GPU policy from its pinned runtime DTB."""
import argparse
import hashlib
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
DTB = ROOT / 'sysinfo/live.dtb'
GPU = '/soc/qcom,kgsl-3d0@3d00000'
PIN = 'd00767f2068d0df73fc2a077de750bba66a5420c77414db1441ff09f6f3ec223'


def get(path, prop):
    return [int(x, 16) for x in subprocess.check_output(
        ['fdtget', '-t', 'x', DTB, path, prop], text=True).split()]


def children(path):
    return subprocess.check_output(['fdtget', '-l', DTB, path], text=True).splitlines()


def generate():
    if hashlib.sha256(DTB.read_bytes()).hexdigest() != PIN:
        raise ValueError('PKX110 DTB differs from the pinned source')
    rows = ['/* SPDX-License-Identifier: MIT */',
            '/* Generated by prepare-gpu-opps.py from sysinfo/live.dtb; do not hand-edit. */',
            '#pragma once', '#include <stdint.h>',
            'typedef struct {uint32_t hz,level,bandwidth;} PaganiGpuOpp;',
            'typedef struct {uint32_t speed_bin,sku[2],initial,count;PaganiGpuOpp opps[16];} PaganiGpuProfile;',
            'static const PaganiGpuProfile pagani_gpu_profiles[] = {']
    base = GPU + '/qcom,gpu-pwrlevel-bins'
    for name in children(base):
        node = base + '/' + name
        props = subprocess.check_output(['fdtget', '-p', DTB, node], text=True).splitlines()
        speed = get(node, 'qcom,speed-bin')[0] if 'qcom,speed-bin' in props else 0xffffffff
        skus = get(node, 'qcom,sku-codes') if 'qcom,sku-codes' in props else [0, 0]
        if len(skus) != 2:
            raise ValueError('Unexpected SKU selector')
        levels = []
        for child in children(node):
            p = node + '/' + child
            levels.append((get(p, 'reg')[0], get(p, 'qcom,gpu-freq')[0],
                           get(p, 'qcom,level')[0], get(p, 'qcom,bus-freq')[0]))
        initial = next(x[1] for x in levels if x[0] == get(node, 'qcom,initial-pwrlevel')[0])
        opps = [(0, 0, 0)] + sorted(set(x[1:] for x in levels))
        if len(opps) > 16 or len({x[0] for x in opps}) != len(opps):
            raise ValueError('Ambiguous GPU frequency policy')
        initial = next(i for i, x in enumerate(opps) if x[0] == initial)
        rows.append('    {%su,{%s},%du,%du,{' % (speed, ','.join(str(x)+'u' for x in skus), initial, len(opps)))
        rows += ['        {%du,%du,%du},' % x for x in opps]
        rows.append('    }},')
    rows += ['};', 'static const uint32_t pagani_gpu_bandwidths[] = {' +
             ','.join(str(x)+'u' for x in get(GPU, 'qcom,bus-table-ddr')) + '};']
    gmu = get('/soc/qcom,gmu@3d37000', 'qcom,gmu-freq-table')
    if len(gmu) != 4:
        raise ValueError('Unexpected GMU frequency table')
    rows += ['static const PaganiGpuOpp pagani_gmu_opps[] = {{0,0,0},' +
             ','.join('{%du,%du,0}' % tuple(gmu[i:i+2]) for i in (0, 2)) + '};']
    return '\n'.join(rows) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = ROOT / 'package/PaganiGpuOpps.h'
    content = generate()
    if args.check:
        if output.read_text() != content:
            raise SystemExit('GPU OPP header differs from pinned DTB')
    else:
        output.write_text(content)
    print('PASS: six PKX110 GPU policies and GMU/DDR tables match the pinned DTB')
